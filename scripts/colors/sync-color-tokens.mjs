import fs from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

import postcss from "postcss"

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const canonicalPath = path.join(
  repositoryRoot,
  "apps/web/src/shared/styles/color-tokens.css",
)
const targets = [
  path.join(repositoryRoot, "apps/server/src/features/desktop-auth/routes.ts"),
  path.join(repositoryRoot, "apps/desktop/src-tauri/src/auth/oauth.rs"),
]
const tokenNames = [
  "--zb-color-surface-background-canvas",
  "--zb-color-surface-background-muted",
  "--zb-color-content-text-primary",
  "--zb-color-content-text-secondary",
  "--zb-color-border-stroke-default",
  "--zb-color-control-background-default",
  "--zb-color-control-border-default",
  "--zb-color-action-background-primary",
  "--zb-color-action-background-primary-hover",
  "--zb-color-action-text-on-primary",
  "--zb-color-action-text-link",
  "--zb-color-action-background-secondary",
  "--zb-color-action-text-on-secondary",
  "--zb-color-action-background-neutral-hover",
]
const markerPattern = /\/\* COLOR_TOKENS_START:[\s\S]*?\/\* COLOR_TOKENS_END \*\//

function declarationsFor(root, selector) {
  const values = new Map()

  root.walkRules((rule) => {
    const selectors = rule.selectors?.map((value) => value.trim()) ?? []
    if (!selectors.includes(selector) || selectors.some((value) => value.includes("["))) {
      return
    }

    rule.walkDecls((declaration) => {
      if (declaration.prop.startsWith("--zb-color-")) {
        values.set(declaration.prop, declaration.value)
      }
    })
  })

  return values
}

function serializeDeclarations(values) {
  return tokenNames
    .map((name) => {
      const value = values.get(name)
      if (!value) throw new Error(`Missing authorization token ${name}`)
      return `${name}:${value}`
    })
    .join(";")
}

const canonicalCss = await fs.readFile(canonicalPath, "utf8")
const root = postcss.parse(canonicalCss, { from: canonicalPath })
const light = declarationsFor(root, ":root")
const dark = new Map(light)
for (const [name, value] of declarationsFor(root, ".dark")) dark.set(name, value)

const generatedFragment = [
  "/* COLOR_TOKENS_START: generated by scripts/colors/sync-color-tokens.mjs; do not edit */",
  `:root{color-scheme:light;${serializeDeclarations(light)}}`,
  `@media (prefers-color-scheme:dark){:root{color-scheme:dark;${serializeDeclarations(dark)}}}`,
  "/* COLOR_TOKENS_END */",
].join("")

const checkOnly = process.argv.includes("--check")
const staleTargets = []

for (const target of targets) {
  const source = await fs.readFile(target, "utf8")
  if (!markerPattern.test(source)) throw new Error(`Generated marker missing in ${target}`)
  const synchronized = source.replace(markerPattern, generatedFragment)

  if (source === synchronized) continue
  if (checkOnly) staleTargets.push(path.relative(repositoryRoot, target))
  else await fs.writeFile(target, synchronized)
}

if (staleTargets.length > 0) {
  throw new Error(
    `Generated color tokens are stale in ${staleTargets.join(", ")}. Run npm run tokens:sync.`,
  )
}
