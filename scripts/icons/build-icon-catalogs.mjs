#!/usr/bin/env node
// Regenerates the icon data used by the web icon picker and by the display-time
// conversion of icons that were saved while Zilobase used Phosphor.
//
//   node scripts/icons/build-icon-catalogs.mjs [--check]

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import * as phosphor from "@phosphor-icons/react";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

import { getSvgDrawingSignature } from "../../apps/web/src/components/ui/icon-svg.ts";
import { mapPhosphorToLucide } from "./phosphor-to-lucide.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const lucideIconsDir = path.join(repositoryRoot, "node_modules/lucide-react/dist/esm/icons");
const phosphorIconsDir = path.join(repositoryRoot, "node_modules/@phosphor-icons/react/dist/csr");
const outputDir = path.join(repositoryRoot, "apps/web/src/components/ui");
const phosphorWeights = ["thin", "light", "regular", "bold", "fill", "duotone"];

const toKebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .toLowerCase();

async function buildLucideCatalog() {
  const files = (await fs.readdir(lucideIconsDir)).filter((file) => file.endsWith(".mjs")).sort();
  const icons = [];
  const names = new Set();

  for (const file of files) {
    const { __iconData } = await import(path.join(lucideIconsDir, file));
    if (!__iconData?.name) continue;
    names.add(__iconData.name);
    for (const alias of __iconData.aliases ?? []) names.add(alias);
    icons.push([__iconData.name, ...(__iconData.aliases ?? [])].join(" "));
  }

  return { catalog: icons, names };
}

function buildLegacyPhosphorTable(lucideNames) {
  const phosphorNames = [];
  return fs.readdir(phosphorIconsDir).then((files) => {
    for (const file of files) if (file.endsWith(".es.js")) phosphorNames.push(file.slice(0, -6));

    const lucide = [];
    const lucideIndex = new Map();
    const signatures = new Map();
    let collisions = 0;
    let unmatched = 0;

    for (const name of phosphorNames.sort()) {
      const Icon = phosphor[name];
      if (!Icon) continue;

      const target = mapPhosphorToLucide(toKebab(name), lucideNames);
      if (!target) unmatched += 1;
      if (target && !lucideIndex.has(target)) {
        lucideIndex.set(target, lucide.length);
        lucide.push(target);
      }
      const index = target ? lucideIndex.get(target) : -1;

      for (const weight of phosphorWeights) {
        const signature = getSvgDrawingSignature(
          renderToStaticMarkup(createElement(Icon, { weight })),
        );
        const existing = signatures.get(signature);
        if (existing !== undefined && existing !== index) collisions += 1;
        if (existing === undefined) signatures.set(signature, index);
      }
    }

    return {
      table: {
        lucide,
        icons: [...signatures].map(([signature, index]) => `${signature}:${index}`).join(","),
      },
      stats: { phosphor: phosphorNames.length, unmatched, signatures: signatures.size, collisions },
    };
  });
}

const checkOnly = process.argv.includes("--check");
const { catalog, names } = await buildLucideCatalog();
const { table, stats } = await buildLegacyPhosphorTable(names);
const lucideVersion = JSON.parse(
  await fs.readFile(path.join(repositoryRoot, "node_modules/lucide-react/package.json"), "utf8"),
).version;

const header = "// Generated by scripts/icons/build-icon-catalogs.mjs. Do not edit.\n";
const outputs = {
  "lucide-icon-catalog.ts": `${header}export const lucideVersion = ${JSON.stringify(lucideVersion)};\n// "name alias alias|name|..."\nexport const lucideIcons = ${JSON.stringify(catalog.join("|"))};\n`,
  "legacy-phosphor-icons.ts": `${header}export const lucideVersion = ${JSON.stringify(lucideVersion)};\nexport const lucideNames: string[] = ${JSON.stringify(table.lucide)};\n// "phosphorDrawingSignature:lucideNameIndex,..." where -1 has no Lucide equivalent.\nexport const phosphorDrawings = ${JSON.stringify(table.icons)};\n`,
};

const stale = [];
for (const [file, content] of Object.entries(outputs)) {
  const target = path.join(outputDir, file);
  const current = await fs.readFile(target, "utf8").catch(() => "");
  if (current === content) continue;
  if (checkOnly) stale.push(file);
  else await fs.writeFile(target, content);
}

console.log(
  `Lucide ${lucideVersion}: ${catalog.length} picker icons. Phosphor: ${stats.phosphor} icons, ${stats.phosphor - stats.unmatched} mapped to Lucide, ${stats.unmatched} use the default icon, ${stats.signatures} drawings, ${stats.collisions} collisions.`,
);
if (stale.length > 0) {
  console.error(
    `Icon data is stale: ${stale.join(", ")}. Run node scripts/icons/build-icon-catalogs.mjs.`,
  );
  process.exitCode = 1;
}
