import { LucideProvider } from "lucide-react";
import { createElement, type PropsWithChildren } from "react";

export type { LucideIcon as Icon } from "lucide-react";

// LucideConfig types size as a number, but icons render any CSS length. 1em keeps
// unsized icons scaling with their surrounding text.
const appIconDefaults = {
  size: "1em" as unknown as number,
  strokeWidth: 1.75,
};

export function AppIconProvider({ children }: PropsWithChildren) {
  return createElement(LucideProvider, { ...appIconDefaults, children });
}

